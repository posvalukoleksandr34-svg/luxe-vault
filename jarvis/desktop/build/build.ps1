<#
  Builds the JARVIS desktop app and its installer on Windows.

    cd desktop
    powershell -ExecutionPolicy Bypass -File build\build.ps1 -ServerUrl https://api.myjarvis.com -Version 1.0.0

  Needs: Python 3.12 (64-bit) and Inno Setup 6 (winget install JRSoftware.InnoSetup).
  Result: desktop\dist\JARVIS-Setup-<version>.exe  (the folder app: desktop\dist\JARVIS\JARVIS.exe)
  Optional code signing: set $env:SIGN_PFX and $env:SIGN_PASSWORD (a code-signing certificate).
#>
param(
    [Parameter(Mandatory = $true)][string]$ServerUrl,
    [string]$Version = "1.0.0",
    [string]$Python = "py -3.12"
)
$ErrorActionPreference = "Stop"
$desktop = Split-Path $PSScriptRoot -Parent
Set-Location $desktop

if ($ServerUrl -notmatch '^https://') { Write-Warning "ServerUrl should be https:// in production (tokens travel over it)" }

# 1. clean build environment
if (-not (Test-Path .venv-build)) { Invoke-Expression "$Python -m venv .venv-build" }
$py = Join-Path $desktop ".venv-build\Scripts\python.exe"
& $py -m pip install --upgrade pip | Out-Null
& $py -m pip install -r requirements-app.txt "pyinstaller>=6.10"
if ($LASTEXITCODE -ne 0) { throw "pip install failed" }

# 2. bake the server address and version into the app
Set-Content -Encoding ascii -Path app\_build.py -Value @(
    '"""Generated by build.ps1 - do not edit."""',
    "SERVER_URL = `"$($ServerUrl.TrimEnd('/'))`"",
    "VERSION = `"$Version`""
)
$v = ($Version.Split('.') + @('0', '0', '0', '0'))[0..3] -join ', '
@"
VSVersionInfo(
  ffi=FixedFileInfo(filevers=($v), prodvers=($v)),
  kids=[StringFileInfo([StringTable('040904B0', [
    StringStruct('CompanyName', 'JARVIS'), StringStruct('FileDescription', 'JARVIS desktop assistant'),
    StringStruct('FileVersion', '$Version'), StringStruct('ProductName', 'JARVIS'),
    StringStruct('ProductVersion', '$Version'), StringStruct('OriginalFilename', 'JARVIS.exe')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])]
)
"@ | Set-Content -Encoding utf8 build\version.txt

# 3. wake-word models ("hey jarvis" + feature models) into the openwakeword package, so they get bundled
& $py -c "import openwakeword.utils as u; u.download_models(['hey_jarvis'])"
if ($LASTEXITCODE -ne 0) { throw "could not download the wake-word model" }

# 4. freeze
& $py -m PyInstaller build\jarvis.spec --noconfirm --clean --distpath dist --workpath build\work
if ($LASTEXITCODE -ne 0) { throw "PyInstaller failed" }

function Sign($file) {
    if ($env:SIGN_PFX) {
        & signtool sign /f $env:SIGN_PFX /p $env:SIGN_PASSWORD /fd SHA256 /tr http://timestamp.digicert.com /td SHA256 $file
        if ($LASTEXITCODE -ne 0) { throw "signing failed: $file" }
    }
}
Sign "dist\JARVIS\JARVIS.exe"

# 5. installer
$iscc = @("${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe", "$env:ProgramFiles\Inno Setup 6\ISCC.exe", "$env:LOCALAPPDATA\Programs\Inno Setup 6\ISCC.exe") |
    Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $iscc) { throw "Inno Setup 6 not found (winget install JRSoftware.InnoSetup)" }
& $iscc "/DAppVersion=$Version" build\installer.iss
if ($LASTEXITCODE -ne 0) { throw "Inno Setup failed" }
Sign "dist\JARVIS-Setup-$Version.exe"
Write-Host "OK: dist\JARVIS-Setup-$Version.exe  (server: $ServerUrl)"
